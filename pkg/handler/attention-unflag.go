package handler

import (
	"context"
	"net/http"

	"github.com/bborbe/errors"
	libhttp "github.com/bborbe/http"
	"github.com/gorilla/mux"

	"github.com/bborbe/attention-controller/pkg"
)

// NewAttentionUnflagHandler creates an HTTP handler that clears an item's flag.
//
// The route takes no body, and unflagging is reversible and idempotent: an item
// that carries no flag is already in the requested state, so the call succeeds
// as a no-op rather than refusing.
func NewAttentionUnflagHandler(store pkg.AttentionStore) http.Handler {
	return libhttp.NewJSONErrorHandler(
		libhttp.WithErrorFunc(
			func(ctx context.Context, resp http.ResponseWriter, req *http.Request) error {
				return handleAttentionUnflag(ctx, resp, req, store)
			},
		),
	)
}

func handleAttentionUnflag(
	ctx context.Context,
	resp http.ResponseWriter,
	req *http.Request,
	store pkg.AttentionStore,
) error {
	itemID := pkg.ItemID(mux.Vars(req)["itemID"])
	if itemID == "" {
		return libhttp.WrapWithCode(
			errors.New(ctx, "itemID is empty"),
			libhttp.ErrorCodeValidation,
			http.StatusBadRequest,
		)
	}
	item, err := store.Unflag(ctx, itemID)
	if err != nil {
		return wrapFlagError(ctx, err, itemID, "unflag failed")
	}
	if err := libhttp.SendJSONResponse(ctx, resp, item, http.StatusOK); err != nil {
		return errors.Wrap(ctx, err, "send response failed")
	}
	return nil
}
